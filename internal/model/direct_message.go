package model

import "time"

// Follow records a directional social relationship: FollowerID follows FolloweeID.
type Follow struct {
	ID         int64     `json:"id" db:"id"`
	FollowerID int64     `json:"follower_id" db:"follower_id"`
	FolloweeID int64     `json:"followee_id" db:"followee_id"`
	Status     int8      `json:"status" db:"status"`
	CreateTime time.Time `json:"create_time" db:"create_time"`
	UpdateTime time.Time `json:"update_time" db:"update_time"`
}

// UserRelation is returned to the UI before it opens a direct-message window.
type UserRelation struct {
	Following  bool `json:"following"`
	FollowedBy bool `json:"followed_by"`
	Mutual     bool `json:"mutual"`
}

// Conversation is a unique one-to-one conversation. UserLowID is always lower
// than UserHighID, which lets the database enforce one row per user pair.
type Conversation struct {
	ID int64 `json:"id" db:"id"`
	// UserLowID is the ID of the user with the lower ID in the conversation.
	// UserHighID is the ID of the user with the higher ID in the conversation.
	UserLowID       int64     `json:"user_low_id" db:"user_low_id"` // 小id 放前面；一方面保证数据库中同一个对话只有一条记录，另一方面保证 user_low_id 和 user_high_id 的顺序不变，方便后续的查询
	UserHighID      int64     `json:"user_high_id" db:"user_high_id"`
	LastMessageID   int64     `json:"last_message_id" db:"last_message_id"`
	LastMessageTime time.Time `json:"last_message_time" db:"last_message_time"`
	CreateTime      time.Time `json:"create_time" db:"create_time"`
	UpdateTime      time.Time `json:"update_time" db:"update_time"`
}

// DirectMessage is the durable message record. ClientMessageID is generated by
// the client and provides idempotency when a request is retried.
type DirectMessage struct {
	ID              int64     `json:"id" db:"id"`
	ConversationID  int64     `json:"conversation_id" db:"conversation_id"`
	SenderID        int64     `json:"sender_id" db:"sender_id"`
	ReceiverID      int64     `json:"receiver_id" db:"receiver_id"`
	ClientMessageID string    `json:"client_message_id" db:"client_message_id"`
	Content         string    `json:"content" db:"content"`
	MessageType     int8      `json:"message_type" db:"message_type"`
	Status          int8      `json:"status" db:"status"`
	CreateTime      time.Time `json:"create_time" db:"create_time"`
}

// ConversationSummary is shaped for the conversation-list page.
type ConversationSummary struct {
	ConversationID int64 `json:"conversation_id" db:"conversation_id"`
	PeerID         int64 `json:"peer_id" db:"peer_id"`
	// PeerID是当前用户私信的对方用户的ID，PeerUsername是当前用户私信的对方用户的用户名;
	// 用于在会话列表中显示对方名称，避免前端再次查询用户信息
	PeerUsername  string    `json:"peer_username" db:"peer_username"`
	LastMessage   string    `json:"last_message" db:"last_message"`
	LastMessageID int64     `json:"last_message_id" db:"last_message_id"`
	LastMessageAt time.Time `json:"last_message_at" db:"last_message_at"`
	UnreadCount   int64     `json:"unread_count" db:"unread_count"`
}

// SendMessagePolicy describes why a send was allowed and what the UI should
// display after it succeeds.
type SendMessagePolicy struct {
	Mutual            bool  `json:"mutual"`
	StrangerSentCount int64 `json:"stranger_sent_count"`
	StrangerRemaining int64 `json:"stranger_remaining"`
	WaitingForReply   bool  `json:"waiting_for_reply"`
}

type SendMessageResult struct {
	Message  *DirectMessage    `json:"message"`
	Policy   SendMessagePolicy `json:"policy"`
	OutboxID int64             `json:"-"`
}
